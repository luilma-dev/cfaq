export type Subject = 'portugues' | 'matematica';
export type Question = {
  id: string;
  lessonId: string;
  prompt: string;
  options: string[];
  answer: number;
  explanation: string;
};
export type Lesson = {
  id: string;
  subject: Subject;
  title: string;
  subtitle: string;
  week: number;
  minutes: number;
  pages: string;
  theory: string[];
  example: string;
  tip: string;
  questions: Question[];
};
type QuestionInput = [
  prompt: string,
  correct: string,
  wrong1: string,
  wrong2: string,
  wrong3: string,
  explanation: string,
];

function lesson(
  subject: Subject,
  number: number,
  week: number,
  title: string,
  subtitle: string,
  pages: string,
  theory: string[],
  example: string,
  tip: string,
  inputs: QuestionInput[],
): Lesson {
  const id = `${subject === 'portugues' ? 'pt' : 'mt'}-${String(number).padStart(2, '0')}`;
  return {
    id,
    subject,
    week,
    title,
    subtitle,
    pages,
    theory,
    example,
    tip,
    minutes: 12,
    questions: inputs.map(([prompt, correct, ...rest], i) => {
      const explanation = rest.pop()!;
      const answer = (number + i) % 4;
      const options = [...rest];
      options.splice(answer, 0, correct);
      return { id: `${id}-q${i + 1}`, lessonId: id, prompt, options, answer, explanation };
    }),
  };
}

